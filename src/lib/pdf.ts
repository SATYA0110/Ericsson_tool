import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { AlarmSummary, BbuReport, CommandResult } from "@/types";

function formatDateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-GB", {
    year: "numeric",
    month: "short",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function generateReportPdf(report: BbuReport) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;

  // Header band
  doc.setFillColor(15, 60, 90);
  doc.rect(0, 0, pageWidth, 26, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Ericsson BBU Site Health Report", margin, 12);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`Site: ${report.site_name}   |   Host: ${report.host} (${report.protocol.toUpperCase()})`, margin, 19);

  // Report details block
  autoTable(doc, {
    startY: 32,
    theme: "grid",
    styles: { fontSize: 9, cellPadding: 2 },
    headStyles: { fillColor: [15, 60, 90], textColor: 255 },
    head: [["Field", "Value"]],
    body: [
      ["Site name", report.site_name],
      ["Node host", report.host],
      ["Protocol", report.protocol.toUpperCase()],
      ["Login user", report.username],
      ["Engineer", report.engineer || "-"],
      ["Collected at", formatDateTime(report.created_at)],
      ["Collection status", report.status.toUpperCase()],
      ...(report.error ? [["Error", report.error]] : []),
    ],
  });

  let cursor = (doc as any).lastAutoTable.finalY + 6;

  // Alarm summary section
  if (report.alarm_summary) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(0, 0, 0);
    doc.text("Alarm Summary", margin, cursor);
    cursor += 3;
    const s: AlarmSummary = report.alarm_summary;
    autoTable(doc, {
      startY: cursor,
      theme: "grid",
      styles: { fontSize: 9, cellPadding: 2, halign: "center" },
      headStyles: { fillColor: [15, 60, 90], textColor: 255 },
      head: [["Critical", "Major", "Minor", "Warning"]],
      body: [[String(s.critical), String(s.major), String(s.minor), String(s.warning)]],
    });
    cursor = (doc as any).lastAutoTable.finalY + 8;
  }

  // Per-command sections
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Command Output", margin, cursor);
  cursor += 4;

  const results: CommandResult[] = report.results || [];
  for (const r of results) {
    if (cursor > doc.internal.pageSize.getHeight() - 40) {
      doc.addPage();
      cursor = 20;
    }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(15, 60, 90);
    doc.text(`${r.title}  (${r.command})`, margin, cursor);
    cursor += 3;
    doc.setFont("courier", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(40, 40, 40);
    const lines = doc.splitTextToSize(r.output || "(no output)", pageWidth - margin * 2);
    const lineHeight = 3.6;
    for (const line of lines) {
      if (cursor > doc.internal.pageSize.getHeight() - 20) {
        doc.addPage();
        cursor = 20;
      }
      doc.text(line, margin, cursor);
      cursor += lineHeight;
    }
    cursor += 5;
  }

  // Footer on each page
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(120);
    doc.text(
      `Generated by BBU Report Tool - Page ${i} of ${pageCount}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 8,
      { align: "center" },
    );
  }

  const safe = report.site_name.replace(/[^a-z0-9]+/gi, "_").toLowerCase();
  doc.save(`${safe}_bbu_report_${report.created_at.slice(0, 10)}.pdf`);
}
